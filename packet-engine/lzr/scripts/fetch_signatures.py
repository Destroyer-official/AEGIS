def main():
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(["category", "protocol", "signature", "priority"])
    seen = set()
    count = 0
    for cat, proto, sig, prio in SIGNATURES:
        key = (cat, proto, sig)
        if key in seen:
            continue
        seen.add(key)
        writer.writerow([cat, proto, sig, prio])
        count += 1
    sys.stdout.write(output.getvalue())
    print(f"# Total unique signatures: {count}", file=sys.stderr)


if __name__ == "__main__":
    main()
